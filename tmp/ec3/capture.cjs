const { chromium } = require('@playwright/test');
const path = require('path');
const http=require('http'),fs=require('fs/promises');
const root=path.resolve(__dirname,'../..');
const server=http.createServer(async(req,res)=>{try{let f=path.join(root,new URL(req.url,'http://localhost').pathname);if((await fs.stat(f)).isDirectory())f=path.join(f,'index.html');res.setHeader('Content-Type',({'.js':'text/javascript','.mjs':'text/javascript','.css':'text/css','.html':'text/html','.svg':'image/svg+xml'})[path.extname(f)]||'application/octet-stream');res.end(await fs.readFile(f));}catch{res.writeHead(404).end();}}).listen(4188,'127.0.0.1');
(async () => {
 await new Promise(r=>setTimeout(r,1000));
 const browser = await chromium.launch({channel:'msedge',headless:true});
 const page = await browser.newPage({viewport:{width:1280,height:800},deviceScaleFactor:1});
 page.on('pageerror',e=>console.log('PAGEERROR',e.message));
 page.on('console',msg=>{if(msg.type()==='error')console.log('CONSOLE',msg.text())});
 await page.goto('http://127.0.0.1:4188');
 await page.waitForTimeout(2000);
 console.log((await page.locator('body').innerText()).slice(0,1200));
 await page.getByRole('button',{name:/Entrar como propietario/}).click();
 await page.getByRole('heading',{name:'Todo lo importante, a mano.'}).waitFor();
 await page.waitForTimeout(3500);
 await page.screenshot({path:path.join(__dirname,'inicio.png')});
 await page.goto('http://127.0.0.1:4188/#/alerts');
 await page.locator('.alert-card').filter({hasText:'Nube'}).getByRole('link',{name:/Abrir caso/}).click();
 await page.waitForTimeout(4000);
 await page.locator('.overview-map').screenshot({path:path.join(__dirname,'mapa.png')});
 await page.goto('http://127.0.0.1:4188/#/home');
 await page.getByRole('button',{name:/Registrar mascota/}).click();
 await page.getByRole('dialog').screenshot({path:path.join(__dirname,'ficha.png')});
 await page.getByRole('button',{name:'Cancelar',exact:true}).click();
 await page.goto('http://127.0.0.1:4188/#/locations');
 await page.waitForTimeout(700);
 await page.screenshot({path:path.join(__dirname,'ubicaciones.png')});
 await page.goto('http://127.0.0.1:4188/#/notifications');
 await page.waitForTimeout(700);
 await page.screenshot({path:path.join(__dirname,'avisos.png')});
 await browser.close();
 server.close();
 console.log('4 capturas de la version actual con datos de demostracion');
})().catch(e=>{server.close();console.error(e);process.exit(1)});
